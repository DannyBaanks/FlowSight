#!/usr/bin/env python3
"""Synthetic, deterministic demos. No external source images are reused."""
from pathlib import Path
from PIL import Image, ImageDraw
ROOT=Path(__file__).resolve().parent

# Sprite: 64x48, 5 discrete visual colors + alpha, geometric regions.
sprite=Image.new('RGBA',(64,48),(12,12,18,255))
d=ImageDraw.Draw(sprite)
d.rectangle((4,8,29,33),fill=(46,204,113,255))
d.rectangle((35,8,57,33),fill=(231,76,60,255))
d.rectangle((8,12,25,15),fill=(246,221,74,255))
d.rectangle((39,12,53,15),fill=(246,221,74,255))
d.rectangle((14,22,20,26),fill=(235,235,245,255))
d.rectangle((43,22,49,26),fill=(235,235,245,255))
sprite.save(ROOT/'sprite.png')
changed=sprite.copy()
ImageDraw.Draw(changed).rectangle((16,24,18,24),fill=(255,0,255,255))
changed.save(ROOT/'sprite_edited.png')

# Faithful pixel recipe for public FLOW README/core example make_hello_flow;
# not generated by importing FLOW's VM, and not an executed flow.
flow=Image.new('RGB',(32,16),(128,128,0))
for x in range(2,11):flow.putpixel((x,2),(255,128,0))
for x in range(3,8):flow.putpixel((x,2),(255,128,2))
flow.putpixel((8,2),(255,128,5))
flow.putpixel((9,2),(255,128,0))
flow.putpixel((2,2),(255,128,255))
flow.save(ROOT/'flow_hello.png')
print('Generated examples/sprite.png, sprite_edited.png, flow_hello.png')
